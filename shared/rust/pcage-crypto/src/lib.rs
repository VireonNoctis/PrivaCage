#![forbid(unsafe_code)]

//! Portable implementation of the PCAGE01 encrypted profile envelope.
//!
//! Wire-format details and cross-language test vectors live in the repository's
//! docs/encrypted-profile-format.md and shared/crypto/test-vectors directory.

use aes_gcm::{
    Aes256Gcm, KeyInit, Nonce,
    aead::{Aead, Payload},
};
use argon2::{Algorithm, Argon2, Params, Version};
use std::{error::Error as StdError, fmt};
use zeroize::Zeroizing;

pub mod profile;

pub const MIN_PASSPHRASE_UTF16_UNITS: usize = 12;
pub const MAX_PASSPHRASE_UTF16_UNITS: usize = 1_024;
pub const MAX_PASSPHRASE_UTF8_BYTES: usize = 4_096;
pub const MAX_PLAINTEXT_BYTES: usize = 1_048_576;
pub const MAX_ENVELOPE_BYTES: usize = MAX_PLAINTEXT_BYTES + 52;

const MAGIC: [u8; 8] = *b"PCAGE01\0";
const MAGIC_SIZE: usize = MAGIC.len();
const SALT_SIZE: usize = 16;
const NONCE_SIZE: usize = 12;
const KEY_SIZE: usize = 32;
const TAG_SIZE: usize = 16;
const HEADER_SIZE: usize = MAGIC_SIZE + SALT_SIZE + NONCE_SIZE;
const ARGON2_MEMORY_KIB: u32 = 19_456;
const ARGON2_ITERATIONS: u32 = 2;
const ARGON2_PARALLELISM: u32 = 1;

/// Failures are deliberately coarse so callers can present a safe, non-secret-bearing
/// message without logging passwords, keys, file contents, or cryptographic internals.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CryptoError {
    InvalidInput(&'static str),
    UnsupportedFormat,
    RandomSourceFailure,
    KeyDerivationFailure,
    EncryptionFailure,
    AuthenticationFailure,
}

impl fmt::Display for CryptoError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::InvalidInput(message) => formatter.write_str(message),
            Self::UnsupportedFormat => formatter.write_str("unsupported PCAGE format"),
            Self::RandomSourceFailure => {
                formatter.write_str("operating-system random source failed")
            }
            Self::KeyDerivationFailure => formatter.write_str("passphrase key derivation failed"),
            Self::EncryptionFailure => formatter.write_str("profile encryption failed"),
            Self::AuthenticationFailure => {
                formatter.write_str("passphrase is incorrect or the envelope was modified")
            }
        }
    }
}

impl StdError for CryptoError {}

/// Encrypts bytes in the PCAGE01 format.
///
/// The exported envelope is magic || salt || nonce || AES-256-GCM(ciphertext || tag),
/// with the 36-byte header authenticated as associated data. Salt and nonce are freshly
/// generated by the operating system CSPRNG for each call.
///
/// The passphrase is exact UTF-8 text; no Unicode normalization is performed. The caller
/// retains ownership of the passphrase and is responsible for its lifetime.
pub fn encrypt(plaintext: &[u8], passphrase: &str) -> Result<Vec<u8>, CryptoError> {
    if plaintext.len() > MAX_PLAINTEXT_BYTES {
        return Err(CryptoError::InvalidInput(
            "profile data exceeds the maximum supported size",
        ));
    }
    validate_passphrase(passphrase)?;

    let mut salt = Zeroizing::new([0_u8; SALT_SIZE]);
    let mut nonce_bytes = Zeroizing::new([0_u8; NONCE_SIZE]);
    getrandom::fill(&mut salt[..]).map_err(|_| CryptoError::RandomSourceFailure)?;
    getrandom::fill(&mut nonce_bytes[..]).map_err(|_| CryptoError::RandomSourceFailure)?;

    let key = derive_key(passphrase, &salt[..])?;
    let cipher = Aes256Gcm::new_from_slice(&key[..]).map_err(|_| CryptoError::EncryptionFailure)?;
    let nonce = Nonce::try_from(&nonce_bytes[..]).map_err(|_| CryptoError::EncryptionFailure)?;

    let mut envelope = Vec::with_capacity(HEADER_SIZE + plaintext.len() + TAG_SIZE);
    envelope.extend_from_slice(&MAGIC);
    envelope.extend_from_slice(&salt[..]);
    envelope.extend_from_slice(&nonce_bytes[..]);

    let ciphertext = cipher
        .encrypt(
            &nonce,
            Payload {
                msg: plaintext,
                aad: &envelope[..HEADER_SIZE],
            },
        )
        .map_err(|_| CryptoError::EncryptionFailure)?;
    envelope.extend_from_slice(&ciphertext);

    Ok(envelope)
}

/// Decrypts a PCAGE01 envelope only after its length, magic, and GCM tag validate.
///
/// The returned plaintext is allocated only after authenticated decryption succeeds.
pub fn decrypt(envelope: &[u8], passphrase: &str) -> Result<Vec<u8>, CryptoError> {
    if !(HEADER_SIZE + TAG_SIZE..=MAX_ENVELOPE_BYTES).contains(&envelope.len()) {
        return Err(CryptoError::InvalidInput(
            "encrypted backup length is invalid",
        ));
    }
    if envelope[..MAGIC_SIZE] != MAGIC {
        return Err(CryptoError::UnsupportedFormat);
    }
    validate_passphrase(passphrase)?;

    let header = &envelope[..HEADER_SIZE];
    let salt = &envelope[MAGIC_SIZE..MAGIC_SIZE + SALT_SIZE];
    let nonce_bytes = &envelope[MAGIC_SIZE + SALT_SIZE..HEADER_SIZE];
    let key = derive_key(passphrase, salt)?;
    let cipher =
        Aes256Gcm::new_from_slice(&key[..]).map_err(|_| CryptoError::AuthenticationFailure)?;
    let nonce = Nonce::try_from(nonce_bytes).map_err(|_| CryptoError::AuthenticationFailure)?;

    cipher
        .decrypt(
            &nonce,
            Payload {
                msg: &envelope[HEADER_SIZE..],
                aad: header,
            },
        )
        .map_err(|_| CryptoError::AuthenticationFailure)
}

fn validate_passphrase(passphrase: &str) -> Result<(), CryptoError> {
    let utf16_units = passphrase.encode_utf16().count();
    if !(MIN_PASSPHRASE_UTF16_UNITS..=MAX_PASSPHRASE_UTF16_UNITS).contains(&utf16_units) {
        return Err(CryptoError::InvalidInput(
            "passphrase must contain 12 to 1024 UTF-16 code units",
        ));
    }
    if passphrase.len() > MAX_PASSPHRASE_UTF8_BYTES {
        return Err(CryptoError::InvalidInput(
            "passphrase exceeds the maximum UTF-8 byte length",
        ));
    }
    Ok(())
}

fn derive_key(passphrase: &str, salt: &[u8]) -> Result<Zeroizing<[u8; KEY_SIZE]>, CryptoError> {
    let params = Params::new(
        ARGON2_MEMORY_KIB,
        ARGON2_ITERATIONS,
        ARGON2_PARALLELISM,
        Some(KEY_SIZE),
    )
    .map_err(|_| CryptoError::KeyDerivationFailure)?;
    let argon2 = Argon2::new(Algorithm::Argon2id, Version::V0x13, params);
    let mut key = Zeroizing::new([0_u8; KEY_SIZE]);
    argon2
        .hash_password_into(passphrase.as_bytes(), salt, &mut *key)
        .map_err(|_| CryptoError::KeyDerivationFailure)?;
    Ok(key)
}

#[cfg(test)]
mod tests {
    use super::*;
    use zeroize::Zeroize;

    const VECTOR_ENVELOPE_HEX: &str =
        include_str!("../../../crypto/test-vectors/pcage-v1-envelope.hex");
    const VECTOR_PLAINTEXT: &[u8] =
        include_bytes!("../../../crypto/test-vectors/pcage-v1-plaintext.json");
    const TEST_PASSPHRASE: &str = "correct horse battery staple";

    fn decode_hex(value: &str) -> Vec<u8> {
        let digits: Vec<u8> = value
            .bytes()
            .filter(|byte| !byte.is_ascii_whitespace())
            .collect();
        assert_eq!(
            digits.len() % 2,
            0,
            "hex fixture has an odd number of digits"
        );
        digits
            .chunks_exact(2)
            .map(|pair| {
                let high = (pair[0] as char)
                    .to_digit(16)
                    .expect("valid high hex digit");
                let low = (pair[1] as char).to_digit(16).expect("valid low hex digit");
                ((high << 4) | low) as u8
            })
            .collect()
    }

    #[test]
    fn decrypts_shared_kotlin_interoperability_vector() {
        let envelope = decode_hex(VECTOR_ENVELOPE_HEX);
        let plaintext = decrypt(&envelope, TEST_PASSPHRASE).expect("known-answer vector decrypts");
        assert_eq!(plaintext.as_slice(), VECTOR_PLAINTEXT);
    }

    #[test]
    fn round_trips_binary_payload() {
        let mut plaintext = vec![0, 1, 2, 0, 255, 128, 42];
        let envelope = encrypt(&plaintext, TEST_PASSPHRASE).expect("encrypt succeeds");
        let mut decrypted = decrypt(&envelope, TEST_PASSPHRASE).expect("decrypt succeeds");
        assert_eq!(decrypted, plaintext);
        plaintext.zeroize();
        decrypted.zeroize();
    }

    #[test]
    fn each_encryption_uses_a_fresh_salt_and_nonce() {
        let first = encrypt(b"profile", TEST_PASSPHRASE).expect("first encryption");
        let second = encrypt(b"profile", TEST_PASSPHRASE).expect("second encryption");
        assert_ne!(&first[..HEADER_SIZE], &second[..HEADER_SIZE]);
    }

    #[test]
    fn rejects_wrong_passphrase() {
        let envelope = encrypt(b"profile", TEST_PASSPHRASE).expect("encrypt succeeds");
        assert_eq!(
            decrypt(&envelope, "a different strong passphrase"),
            Err(CryptoError::AuthenticationFailure)
        );
    }

    #[test]
    fn rejects_modified_authenticated_header_and_ciphertext() {
        let original = encrypt(b"profile", TEST_PASSPHRASE).expect("encrypt succeeds");
        let mut changed_header = original.clone();
        changed_header[8] ^= 1;
        assert_eq!(
            decrypt(&changed_header, TEST_PASSPHRASE),
            Err(CryptoError::AuthenticationFailure)
        );

        let mut changed_ciphertext = original;
        let payload_index = changed_ciphertext.len() - TAG_SIZE - 1;
        changed_ciphertext[payload_index] ^= 1;
        assert_eq!(
            decrypt(&changed_ciphertext, TEST_PASSPHRASE),
            Err(CryptoError::AuthenticationFailure)
        );
    }

    #[test]
    fn rejects_mutation_of_every_authenticated_header_byte() {
        let original =
            encrypt(b"header authentication", TEST_PASSPHRASE).expect("encrypt succeeds");
        for index in MAGIC_SIZE..HEADER_SIZE {
            let mut modified = original.clone();
            modified[index] ^= 1;
            assert_eq!(
                decrypt(&modified, TEST_PASSPHRASE),
                Err(CryptoError::AuthenticationFailure),
                "modified header byte {index} must fail authentication"
            );
        }
    }

    #[test]
    fn rejects_mutated_ciphertext_and_authentication_tag() {
        let original = encrypt(b"ciphertext integrity", TEST_PASSPHRASE).expect("encrypt succeeds");
        let ciphertext_len = original.len() - HEADER_SIZE;
        let indexes = [
            HEADER_SIZE,
            HEADER_SIZE + ciphertext_len / 2,
            original.len() - 1,
        ];
        for index in indexes {
            let mut modified = original.clone();
            modified[index] ^= 0x80;
            assert_eq!(
                decrypt(&modified, TEST_PASSPHRASE),
                Err(CryptoError::AuthenticationFailure),
                "modified envelope byte {index} must fail authentication"
            );
        }
    }

    #[test]
    fn rejects_unsupported_magic_and_truncated_envelopes() {
        let mut envelope = decode_hex(VECTOR_ENVELOPE_HEX);
        envelope[6] = b'2';
        assert_eq!(
            decrypt(&envelope, TEST_PASSPHRASE),
            Err(CryptoError::UnsupportedFormat)
        );
        assert!(matches!(
            decrypt(&envelope[..20], TEST_PASSPHRASE),
            Err(CryptoError::InvalidInput(_))
        ));
    }

    #[test]
    fn enforces_passphrase_and_plaintext_bounds() {
        assert!(matches!(
            encrypt(b"x", "too short"),
            Err(CryptoError::InvalidInput(_))
        ));
        assert!(matches!(
            encrypt(&vec![0; MAX_PLAINTEXT_BYTES + 1], TEST_PASSPHRASE),
            Err(CryptoError::InvalidInput(_))
        ));
        assert!(matches!(
            encrypt(b"x", &"🦊".repeat(5)),
            Err(CryptoError::InvalidInput(_))
        ));
        assert!(encrypt(b"x", &"🦊".repeat(6)).is_ok());
    }

    #[test]
    fn rejects_out_of_range_envelope_lengths_before_passphrase_processing() {
        let too_short = vec![0_u8; HEADER_SIZE + TAG_SIZE - 1];
        assert!(matches!(
            decrypt(&too_short, "short"),
            Err(CryptoError::InvalidInput(_))
        ));

        let too_large = vec![0_u8; MAX_ENVELOPE_BYTES + 1];
        assert!(matches!(
            decrypt(&too_large, "short"),
            Err(CryptoError::InvalidInput(_))
        ));
    }

    #[test]
    fn exact_minimum_reaches_authentication_and_maximum_round_trips() {
        let mut minimum = vec![0_u8; HEADER_SIZE + TAG_SIZE];
        minimum[..MAGIC_SIZE].copy_from_slice(&MAGIC);
        assert_eq!(
            decrypt(&minimum, TEST_PASSPHRASE),
            Err(CryptoError::AuthenticationFailure)
        );

        let plaintext = vec![0x5a_u8; MAX_PLAINTEXT_BYTES];
        let envelope = encrypt(&plaintext, TEST_PASSPHRASE).expect("maximum plaintext encrypts");
        assert_eq!(envelope.len(), MAX_ENVELOPE_BYTES);
        let decrypted = decrypt(&envelope, TEST_PASSPHRASE).expect("maximum envelope decrypts");
        assert_eq!(decrypted, plaintext);
    }
}
